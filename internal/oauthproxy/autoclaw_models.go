type autoClawLocalContract struct {
	baseURL    string
	version    string
	imageModel string
	models     []autoclawModelDefinition
}

var autoClawRuntimeConfigPath = defaultAutoClawRuntimeConfigPath

func defaultAutoClawRuntimeConfigPath() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, ".openclaw-autoclaw", "openclaw.runtime.json"), nil
}

func loadAutoClawLocalContract() (autoClawLocalContract, error) {
	path, err := autoClawRuntimeConfigPath()
	if err != nil {
		return autoClawLocalContract{}, err
	}
	file, err := os.Open(path)
	if err != nil {
		return autoClawLocalContract{}, err
	}
	defer file.Close()
	raw, err := io.ReadAll(io.LimitReader(file, autoClawRuntimeConfigMaxBytes+1))
	if err != nil {
		return autoClawLocalContract{}, err
	}
	if int64(len(raw)) > autoClawRuntimeConfigMaxBytes {
		return autoClawLocalContract{}, fmt.Errorf("AutoClaw runtime config exceeds %d bytes", autoClawRuntimeConfigMaxBytes)
	}

	type runtimeModel struct {
		ID            string            `json:"id"`
		Name          string            `json:"name"`
		Input         []string          `json:"input"`
		Reasoning     bool              `json:"reasoning"`
		ContextWindow int               `json:"contextWindow"`
		MaxTokens     int               `json:"maxTokens"`
		Headers       map[string]string `json:"headers"`
		Compat        struct {
			RequiresAssistantReasoningContent bool `json:"requiresReasoningContentOnAssistantMessages"`
		} `json:"compat"`
	}
	type runtimeProvider struct {
		BaseURL string         `json:"baseUrl"`
		API     string         `json:"api"`
		Models  []runtimeModel `json:"models"`
	}
	var config struct {
		Models struct {
			Providers map[string]runtimeProvider `json:"providers"`
		} `json:"models"`
		Agents struct {
			Defaults struct {
				ImageModel struct {
					Primary string `json:"primary"`
				} `json:"imageModel"`
			} `json:"defaults"`
		} `json:"agents"`
	}
	if err := json.Unmarshal(raw, &config); err != nil {
		return autoClawLocalContract{}, fmt.Errorf("decode AutoClaw runtime config: %w", err)
	}
	provider, ok := config.Models.Providers["zai"]
	if !ok || (strings.TrimSpace(provider.API) != "" && !strings.EqualFold(strings.TrimSpace(provider.API), "openai-completions")) {
		return autoClawLocalContract{}, fmt.Errorf("AutoClaw runtime config has no zai OpenAI Completions provider")
	}

	contract := autoClawLocalContract{baseURL: strings.TrimRight(strings.TrimSpace(provider.BaseURL), "/")}
	contract.imageModel = strings.TrimSpace(config.Agents.Defaults.ImageModel.Primary)
	if prefix, rest, found := strings.Cut(contract.imageModel, "/"); found && strings.EqualFold(prefix, "zai") {
		contract.imageModel = strings.TrimSpace(rest)
	}
	seen := make(map[string]bool, len(provider.Models))
	for _, model := range provider.Models {
		id := strings.TrimSpace(model.ID)
		key := strings.ToLower(id)
		if id == "" || seen[key] {
			continue
		}
		seen[key] = true
		name := strings.TrimSpace(model.Name)
		if name == "" {
			name = id
		}
		input := make([]string, 0, len(model.Input))
		for _, capability := range model.Input {
			capability = strings.ToLower(strings.TrimSpace(capability))
			if capability != "" {
				input = append(input, capability)
			}
		}
		definition := autoclawModelDefinition{
			id: id, name: name, context: model.ContextWindow, maxOutput: model.MaxTokens,
			input: input, reasoning: model.Reasoning,
			requiresAssistantReasoningContent: model.Compat.RequiresAssistantReasoningContent,
		}
		contract.models = append(contract.models, definition)
		if contract.version == "" {
			for header, value := range model.Headers {
				if strings.EqualFold(strings.TrimSpace(header), "X-Version") {
					contract.version = strings.TrimSpace(value)
					break
				}
			}
		}
	}
	if len(contract.models) == 0 {
		return autoClawLocalContract{}, fmt.Errorf("AutoClaw runtime config has an empty zai model catalog")
	}
	if contract.baseURL != "" && !validAutoClawManagedBaseURL(contract.baseURL) {
		return autoClawLocalContract{}, fmt.Errorf("AutoClaw runtime config has an invalid managed base URL")
	}
	return contract, nil
}

func validAutoClawManagedBaseURL(value string) bool {
	parsed, err := url.Parse(strings.TrimSpace(value))
	if err != nil || !strings.EqualFold(parsed.Scheme, "https") || parsed.Hostname() == "" || parsed.User != nil || parsed.RawQuery != "" || parsed.Fragment != "" {
		return false
	}
	return strings.HasSuffix(strings.TrimRight(parsed.EscapedPath(), "/"), "/autoclaw-proxy/proxy/autoclaw")
}

func autoClawEffectiveContract() (autoClawLocalContract, bool) {
	if contract, err := loadAutoClawLocalContract(); err == nil {
		return contract, true
	}
	return autoClawLocalContract{
		version: autoclawDefaultVersion, imageModel: "zai_auto-fast",
		models: cloneAutoClawModelDefinitions(autoclawFallbackModelCatalog),
	}, false
}

func cloneAutoClawModelDefinitions(models []autoclawModelDefinition) []autoclawModelDefinition {
	cloned := make([]autoclawModelDefinition, len(models))
	copy(cloned, models)
	for index := range cloned {
		cloned[index].input = append([]string(nil), models[index].input...)
	}
	return cloned
}

func autoClawModelDefinition(models []autoclawModelDefinition, model string) (autoclawModelDefinition, bool) {
	model = strings.TrimSpace(model)
	for _, entry := range models {
		if strings.EqualFold(entry.id, model) {
			return entry, true
		}
	}
	return autoclawModelDefinition{}, false
}

func autoClawModelSupportsImage(models []autoclawModelDefinition, model string) bool {
	entry, ok := autoClawModelDefinition(models, model)
	if !ok {
		return false
	}
	for _, capability := range entry.input {
		if strings.EqualFold(capability, "image") {
			return true
		}
	}
	return false
}

func autoClawPreferredImageModel(contract autoClawLocalContract) string {
	if autoClawModelSupportsImage(contract.models, contract.imageModel) {
		return contract.imageModel
	}
	for _, model := range contract.models {
		if autoClawModelSupportsImage(contract.models, model.id) {
			return model.id
		}
	}
	return ""
}

// AutoClawModelCatalog returns the effective managed model catalog. When the
// AutoClaw-generated OpenClaw config exists, it is authoritative; otherwise CCL
// returns its built-in compatibility snapshot.
func AutoClawModelCatalog() []protocol.ModelInfo {
	contract, _ := autoClawEffectiveContract()
	infos := make([]protocol.ModelInfo, 0, len(contract.models))
	for _, model := range contract.models {
		infos = append(infos, protocol.ModelInfo{
			ID:              model.id,
			DisplayName:     model.name,
			ContextWindow:   model.context,
			MaxOutputTokens: model.maxOutput,
		})
	}
	return infos
}

// AutoClawModelIDs returns the effective catalog model IDs in catalog order.
func AutoClawModelIDs() []string {
	contract, _ := autoClawEffectiveContract()
	ids := make([]string, 0, len(contract.models))
	for _, model := range contract.models {
		ids = append(ids, model.id)
	}
	return ids
}

// AutoClawSupportsModel reports whether the effective catalog admits a model
// ID, case-insensitively.
func AutoClawSupportsModel(model string) bool {
	contract, _ := autoClawEffectiveContract()
	model = autoClawCanonicalModelWithCatalog(model, contract.models)
	_, ok := autoClawModelDefinition(contract.models, model)
	return ok
}
