func claudeSessionsServer(t *testing.T) (string, string) {
	t.Helper()
	config := t.TempDir()
	t.Setenv("CLAUDE_CONFIG_DIR", config)
	workspace := t.TempDir()
	real, err := filepath.EvalSymlinks(workspace)
	if err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join(config, "projects", nonAlphanumeric.ReplaceAllString(real, "-"))
	if err := os.MkdirAll(dir, 0o700); err != nil {
		t.Fatal(err)
	}
	id := "0b2947a0-a3fc-4f6a-9f65-9f14ec982d58"
	if err := os.WriteFile(filepath.Join(dir, id+".jsonl"), []byte(transcriptFixture), 0o600); err != nil {
		t.Fatal(err)
	}
	// A transcript in which the user said nothing is not listed.
	if err := os.WriteFile(filepath.Join(dir, "11111111-2222-3333-4444-555555555555.jsonl"), []byte(`{"type":"system"}`+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	httpServer := testServer(t, Config{Token: "secret", Workspace: workspace})
	return httpServer.URL, id
}

func TestClaudeSessionsListAndImport(t *testing.T) {
	base, id := claudeSessionsServer(t)
	status, body := doJSON(t, "GET", base+"/api/claude-sessions", "secret", "")
	var listing struct {
		Sessions []ClaudeSession `json:"sessions"`
	}
	_ = json.Unmarshal(body, &listing)
	if status != http.StatusOK || len(listing.Sessions) != 1 {
		t.Fatalf("list = %d: %s", status, body)
	}
	if got := listing.Sessions[0]; got.ID != id || got.Title != "Main review" || got.Prompts != 2 {
		t.Fatalf("session = %+v", got)
	}

	status, body = doJSON(t, "POST", base+"/api/claude-sessions/import", "secret", `{"id":"`+id+`"}`)
	var meta Meta
	_ = json.Unmarshal(body, &meta)
	if status != http.StatusCreated || meta.ClaudeSessionID != id || meta.Turns != 2 || meta.Title != "Main review" {
		t.Fatalf("import = %d: %s", status, body)
	}
	_, body = doJSON(t, "GET", base+"/api/sessions/"+meta.ID+"/events", "secret", "")
	var events []Event
	_ = json.Unmarshal(body, &events)
	var kinds []string
	for _, event := range events {
		kinds = append(kinds, event.Type)
	}
	want := "user,token,tool_use,tool_result,token,result,user,token,result"
	if strings.Join(kinds, ",") != want {
		t.Fatalf("events = %s, want %s", strings.Join(kinds, ","), want)
	}
	if !strings.Contains(string(events[0].Payload), `"/review main.go"`) {
		t.Fatalf("command prompt = %s", events[0].Payload)
	}
	if strings.Contains(string(body), "sidechain text") || strings.Contains(string(body), "Caveat") {
		t.Fatalf("sidechain or meta lines were imported: %s", body)
	}
	// Events keep the transcript's time, so the page shows its real days.
	if events[0].TS != 1792490401000 {
		t.Fatalf("first event ts = %d", events[0].TS)
	}

	// Importing again opens the same conversation; the list says so.
	status, body = doJSON(t, "POST", base+"/api/claude-sessions/import", "secret", `{"id":"`+id+`"}`)
	if status != http.StatusOK || !strings.Contains(string(body), meta.ID) {
		t.Fatalf("second import = %d: %s", status, body)
	}
	_, body = doJSON(t, "GET", base+"/api/claude-sessions", "secret", "")
	if !strings.Contains(string(body), `"webSession":"`+meta.ID+`"`) {
		t.Fatalf("list does not link the import: %s", body)
	}
	if status, _ := doJSON(t, "POST", base+"/api/claude-sessions/import", "secret", `{"id":"../../etc/passwd"}`); status != http.StatusNotFound {
		t.Fatalf("traversal import = %d", status)
	}
}
