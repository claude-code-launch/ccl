const tables: Record<Lang, Record<MessageKey, string>> = { en, zh };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  const table = tables[lang];
  return (key, vars) => {
    let text = table[key] ?? en[key];
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
    return text;
  };
}

export function resolveLang(configured: string | undefined): Lang {
  if (configured === "zh" || configured === "en") return configured;
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export const I18n = createContext<{ lang: Lang; t: Translate }>({ lang: "en", t: translator("en") });

export const useI18n = () => useContext(I18n);
